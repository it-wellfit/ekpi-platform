#![forbid(unsafe_code)]

//! R3：LegalRuleML 1.0（OASIS Standard, 2021-08-30）compact 匯出器。
//!
//! 依憑（只引用官方核實構件）：`research/legalruleml-notes.md`（簡稱筆記）：
//! - 根元素 `<lrml:LegalRuleML>`（筆記 §2.1；不存在 "LegalSchema"）。
//! - 頂層規定順序 Prefix* → 元資料集合* → Associations* → Statements*
//!   （筆記 §2.1 引 [S1] §5.16 四類順序）。
//! - 來源錨點：`lrml:LegalSource @key @sameAs`（IRI 型）＋
//!   `lrml:Association > lrml:appliesSource @keyref / lrml:toTarget @keyref`
//!   （N:M isomorphism，筆記 §2.7）。**禁用**不存在的
//!   `NormativeSource` / `PrefixDeclaration` / `ExternalReferences`（§2.11）。
//! - 規則本體：`lrml:PrescriptiveStatement > ruleml:Rule (closure) >
//!   lrml:hasStrength > StrictStrength|DefeasibleStrength`、`ruleml:if` /
//!   `ruleml:then > lrml:SuborderList > deontic 節點`
//!   （筆記 §2.4、§2.5、§2.6；deontic 只用 Obligation/Prohibition/Permission/Right）。
//! - 優先序：`lrml:OverrideStatement > lrml:Override @over @under`（§2.4）。
//! - 時間：`lrml:TemporalCharacteristics/TemporalCharacteristic > forStatus
//!   (@iri <vocab>#InForce) + hasStatusDevelopment (Starts/Ends) + atTime
//!   @keyref`；時間實體 `lrml:Times > ruleml:Time > ruleml:Data
//!   xsi:type="xs:dateTime"`（§2.9）。**禁用** `IsActive` / `IsObligated`。
//! - 衝突與例外（conflicts_with / exception_of）：官方 1.0 **無**對應構件
//!   （筆記 §2.11 全文檢索 0 次）→ 以 XML 註解如實登記；不發明構件、
//!   不借用 Override 語義竄改優先序。
//! - 主體角色：deontic 節點內 `ruleml:slot > lrml:Bearer @iri +
//!   ruleml:Var`（筆記 §2.5 官方骨架）。
//! - 違反後果：`lrml:PenaltyStatement` ＋ `lrml:ReparationStatement >
//!   lrml:Reparation > appliesPenalty / toPrescriptiveStatement`（§2.6）。
//!
//! 引擎概念 → LegalRuleML 映射（筆記 §四映射表；侷限如實聲明）：
//! - 條件樹 leaf → `ruleml:Atom`：`ruleml:Rel @iri="ekp:cond-{field}-{op}"` +
//!   `ruleml:Ind`。op 語義（eq/in/exists）在 Rel IRI；清單值以 `;` 連接為
//!   單一 Ind——官方核實構件未含 ruleml:Or/Neg，**不發明**；condition 樹的
//!   `any` / `not` 節點因此**拒匯**（fail-closed）。
//! - `required_before` / `forbidden_after` / `deadline` / `loop_policy` 的
//!   規範內容進 deontic 節點（must-have-before / must-not-be-followed-by /
//!   must-meet-deadline / must-stop-rework）。
//! - `sequencing.on_violation` 非空 → Penalty/Reparation，後果值以
//!   `ekp:violation-consequence-{block|escalate|warn}` 表達。
//! - `decision` / `provenance` 為引擎治理域，非法律規範本體，不匯出
//!   （snapshot 層另有 SHA-256 審計）。
//!
//! 驗證（筆記 §四注意事項 6 的 schema-外自助檢查 + 官方 §7 要求的 XSD
//! 由本倉以真機 XSD 工具另行把關）：`validate_compact_export` 檢查 XML 良構、
//! @key 唯一（xsd:ID）、@keyref/@over/@under 目標可解析、頂層四類順序、
//! 禁用構件名不存在。不引入 XML 解析依賴。

use std::collections::{BTreeMap, BTreeSet};

use crate::engine::Platform;
use crate::rules::{ConditionNode, RuleRecord};

use serde_json::Value;

/// 本倉 vocab/語料命名空間：RFC 2606/6761 `example.org` 保留域（官方規範
/// 範例同樣使用 example 域，如筆記引句 `http://example.legalruleml.org/lrml`）。
const VOCAB_BASE: &str = "http://ekpi.example.org/vocab#";
const CORPUS_BASE: &str = "http://ekpi.example.org/corpus/";
/// 官方狀態 IRI 前綴（筆記 §2.9 原文層的 vocab#InForce / #Starts / #Ends）。
const LRML_VOCAB: &str = "http://docs.oasis-open.org/legalruleml/ns/v1.0/vocab";

/// 規格筆記明文禁用的構件名（1.0 全文檢索 0 次 → 出現即匯出錯誤）。
const FORBIDDEN_NAMES: [&str; 7] = [
    "NormativeSource",
    "PrefixDeclaration",
    "ExternalReferences",
    "LegalSchema",
    "IsActive",
    "IsObligated",
    "applyModality",
];

/// 對整個 active 規則庫生成 compact LegalRuleML 文件；生成後自驗。
pub fn export_legalruleml(platform: &Platform) -> Result<String, String> {
    let mut records: Vec<&RuleRecord> = platform.rules.active_rules().collect();
    records.sort_by(|a, b| (&a.rule_id, &a.rule_version).cmp(&(&b.rule_id, &b.rule_version)));
    let atom_counter = &mut 0usize;

    let mut out = String::new();
    out.push_str(
        "<lrml:LegalRuleML xmlns:lrml=\"http://docs.oasis-open.org/legalruleml/ns/v1.0/\"\n\
         \x20                 xmlns:xsi=\"http://www.w3.org/2001/XMLSchema-instance\"\n\
         \x20                 xmlns:ruleml=\"http://ruleml.org/spec\"\n\
         \x20                 xmlns:xs=\"http://www.w3.org/2001/XMLSchema\">\n",
    );
    out.push_str(
        "  <!-- Generated by EKPI deterministic engine; every construct name\n\
         \x20   follows research/legalruleml-notes.md official set. -->\n",
    );

    // statement 鍵 ps{i}（xsd:ID 必須 NCName；label 放註解）。
    let ps_keys: Vec<String> = (1..=records.len()).map(|i| format!("ps{i}")).collect();
    let label_of =
        |i: usize| -> String { format!("{}@{}", records[i].rule_id, records[i].rule_version) };

    // ── 第 1 類：Prefix（筆記 §2.2：CURIE 前綴僅由 lrml:Prefix 定義）────
    out.push_str(&format!(
        "  <lrml:Prefix pre=\"ekp\" refID=\"{VOCAB_BASE}\"/>\n"
    ));

    // ── 第 2 類：LegalSources ──────────────────────────────────────
    let source_keys = collect_source_keys(&records);
    out.push_str("  <lrml:LegalSources>\n");
    for ((doc, ver, sec), key) in &source_keys {
        out.push_str(&format!(
            "    <!-- {}@{} §{} -->\n    <lrml:LegalSource key=\"{key}\" sameAs=\"{}\"/>\n",
            doc,
            ver,
            sec,
            esc_attr(&corpus_iri(doc, ver, sec))
        ));
    }
    out.push_str("  </lrml:LegalSources>\n");

    // ── 第 2 類：Times（ruleml:Time 實體；筆記 §2.9）────────────────
    let mut dates: BTreeSet<String> = BTreeSet::new();
    for record in &records {
        dates.insert(record.temporal.effective_from.clone());
        if let Some(to) = &record.temporal.effective_to {
            dates.insert(to.clone());
        }
    }
    let mut time_keys: BTreeMap<String, String> = BTreeMap::new();
    out.push_str("  <lrml:Times>\n");
    for (i, date) in dates.iter().enumerate() {
        let stamp = date_in_force_time(date)?;
        let key = format!("t{}", i + 1);
        time_keys.insert(date.clone(), key.clone());
        out.push_str(&format!(
            "    <ruleml:Time key=\"{key}\">\n\
             \x20     <ruleml:Data xsi:type=\"xs:dateTime\">{stamp}</ruleml:Data>\n\
             \x20   </ruleml:Time>\n"
        ));
    }
    out.push_str("  </lrml:Times>\n");

    // ── 第 2 類：TemporalCharacteristics（InForce Starts/Ends）──────
    out.push_str("  <lrml:TemporalCharacteristics key=\"tc-ekp-rules\">\n");
    for (i, record) in records.iter().enumerate() {
        let cid = format!("tc{}", i + 1);
        out.push_str(&comment_line(&label_of(i), 2));
        out.push_str(&format!(
            "    <lrml:TemporalCharacteristic key=\"{cid}-start\">\n\
             \x20     <lrml:forStatus iri=\"{LRML_VOCAB}#InForce\"/>\n\
             \x20     <lrml:hasStatusDevelopment iri=\"{LRML_VOCAB}#Starts\"/>\n\
             \x20     <lrml:atTime keyref=\"#{}\"/>\n\
             \x20   </lrml:TemporalCharacteristic>\n",
            time_keys[&record.temporal.effective_from]
        ));
        if let Some(to) = &record.temporal.effective_to {
            out.push_str(&format!(
                "    <lrml:TemporalCharacteristic key=\"{cid}-end\">\n\
                 \x20     <lrml:forStatus iri=\"{LRML_VOCAB}#InForce\"/>\n\
                 \x20     <lrml:hasStatusDevelopment iri=\"{LRML_VOCAB}#Ends\"/>\n\
                 \x20     <lrml:atTime keyref=\"#{}\"/>\n\
                 \x20   </lrml:TemporalCharacteristic>\n",
                time_keys[to]
            ));
        }
    }
    out.push_str("  </lrml:TemporalCharacteristics>\n");

    // ── 第 3 類：Associations（appliesSource + appliesTemporalCharacteristics
    //    + toTarget；筆記 §2.7 官方骨架）──────────────────────────────
    out.push_str("  <lrml:Associations key=\"assoc-ekp-rules\">\n");
    for (i, record) in records.iter().enumerate() {
        out.push_str(&comment_line(&label_of(i), 4));
        for ((doc, ver, sec), key) in &source_keys {
            if *doc == record.source.document_id
                && *ver == record.source.document_version
                && record_anchor_sections(record).contains(sec)
            {
                out.push_str(&format!("      <lrml:appliesSource keyref=\"#{key}\"/>\n"));
            }
        }
        out.push_str("      <lrml:appliesTemporalCharacteristics keyref=\"#tc-ekp-rules\"/>\n");
        out.push_str(&format!(
            "      <lrml:toTarget keyref=\"#{}\"/>\n",
            ps_keys[i]
        ));
    }
    out.push_str("  </lrml:Associations>\n");

    // ── 第 4 類：Statements ────────────────────────────────────────
    out.push_str("  <lrml:Statements key=\"stmt-ekp-rules\">\n");
    let mut emitted_override_pairs: BTreeSet<(String, String)> = BTreeSet::new();
    for (i, record) in records.iter().enumerate() {
        // 衝突／例外：官方無構件 → 註解如實登記（筆記 §2.11；kind 字面詞
        // 進註解，讓審計者能以 `conflicts_with` / `exception_of` 定位）。
        for (kind, list) in [
            ("conflicts_with", &record.exceptions.conflicts_with),
            ("exception_of", &record.exceptions.exception_of),
        ] {
            if !list.is_empty() {
                out.push_str(&comment_line(
                    &format!(
                        "{}@{}: relation kind {} on {:?} — no dedicated construct exists in LegalRuleML 1.0 (research note §2.11, 0 matches) — logged here only, not remapped to Override",
                        record.rule_id, record.rule_version, kind, list
                    ),
                    2,
                ));
            }
        }
        out.push_str(&render_overrides(
            record,
            &records,
            &ps_keys,
            &mut emitted_override_pairs,
        )?);
        out.push_str(&render_record(record, &ps_keys[i], atom_counter)?);
    }
    out.push_str("  </lrml:Statements>\n");
    out.push_str("</lrml:LegalRuleML>\n");

    validate_compact_export(&out)?;
    Ok(out)
}

/// 一條規則的條款錨點（source.clause_refs ＋ loop_policy 引用節）。
fn record_anchor_sections(record: &RuleRecord) -> Vec<String> {
    let mut sections: Vec<String> = record
        .source
        .clause_refs
        .iter()
        .map(|c| c.section.clone())
        .collect();
    if let Some(lp) = &record.sequencing.loop_policy {
        sections.push(lp.doc_ref.trim_start_matches('§').to_string());
        if let Some(first) = &lp.first_iteration_ref {
            sections.push(first.trim_start_matches('§').to_string());
        }
    }
    sections.sort();
    sections.dedup();
    sections
}

/// (doc, version, section) → ls{i} 鍵（排序去重，順序唯一）。
fn collect_source_keys(records: &[&RuleRecord]) -> BTreeMap<(String, String, String), String> {
    let mut map = BTreeMap::new();
    let mut counter = 0usize;
    for record in records {
        for section in record_anchor_sections(record) {
            let ident = (
                record.source.document_id.clone(),
                record.source.document_version.clone(),
                section,
            );
            map.entry(ident).or_insert_with(|| {
                counter += 1;
                format!("ls{counter}")
            });
        }
    }
    map
}

/// 縮排 XML 註解（`--` 改寫 `- -`；避免註解內意外出現終止符）。
fn comment_line(text: &str, indent: usize) -> String {
    format!("{}<!-- {} -->\n", " ".repeat(indent), esc_comment(text))
}

/// 語料識別 IRI（example 域；字元白名單清洗）。
fn corpus_iri(doc_id: &str, doc_version: &str, section: &str) -> String {
    format!(
        "{CORPUS_BASE}{}/{}#sec-{}",
        iri_segment(doc_id),
        iri_segment(doc_version),
        iri_segment(section)
    )
}

fn iri_segment(value: &str) -> String {
    value
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || matches!(c, '-' | '_' | '.' | '~') {
                c
            } else {
                '_'
            }
        })
        .collect()
}

/// CURIE 本地段字元白名單（與 IRI 片段同值；單一定義點別名）。
fn curie_segment(value: &str) -> String {
    iri_segment(value)
}

/// 生效日期 → xs:dateTime（形狀不符一律 Err，不做寬鬆解析）。
fn date_in_force_time(date: &str) -> Result<String, String> {
    let b = date.as_bytes();
    let ok = b.len() == 10
        && b[..4].iter().all(u8::is_ascii_digit)
        && b[4] == b'-'
        && b[5..7].iter().all(u8::is_ascii_digit)
        && b[7] == b'-'
        && b[8..10].iter().all(u8::is_ascii_digit);
    if !ok {
        return Err(format!(
            "temporal effective date `{date}` is not YYYY-MM-DD — refuse to export (fail-closed)"
        ));
    }
    Ok(format!("{date}T00:00:00"))
}

/// 優先序：`overrides` → 本規則高；`overridden_by` → 對方高。
/// 引用須唯一解析到一筆 active 紀錄；歧義/未登記以註解登記（D-02）。
fn render_overrides(
    record: &RuleRecord,
    records: &[&RuleRecord],
    ps_keys: &[String],
    emitted: &mut BTreeSet<(String, String)>,
) -> Result<String, String> {
    struct Edge {
        higher: bool,
        reference: String,
    }
    let mut out = String::new();
    let mut edges = Vec::new();
    for reference in &record.exceptions.overrides {
        edges.push(Edge {
            higher: true,
            reference: reference.clone(),
        });
    }
    for reference in &record.exceptions.overridden_by {
        edges.push(Edge {
            higher: false,
            reference: reference.clone(),
        });
    }
    for edge in edges {
        let (id, pin) = match edge.reference.split_once('@') {
            Some((id, pin)) => (id.to_string(), Some(pin.to_string())),
            None => (edge.reference.clone(), None),
        };
        let candidates: Vec<usize> = records
            .iter()
            .enumerate()
            .filter(|(_, r)| r.rule_id == id)
            .filter(|(_, r)| pin.as_deref().is_none_or(|p| r.rule_version == p))
            .map(|(i, _)| i)
            .collect();
        let (over, under) = match candidates.len() {
            0 => {
                out.push_str(&comment_line(
                    &format!(
                        "{}@{}: override reference `{}` unresolved (no matching active record) — not emitted, logged only (D-02)",
                        record.rule_id, record.rule_version, edge.reference
                    ),
                    2,
                ));
                continue;
            }
            1 => {
                let other = ps_keys[candidates[0]].clone();
                let self_index = records
                    .iter()
                    .position(|r| {
                        r.rule_id == record.rule_id && r.rule_version == record.rule_version
                    })
                    .expect("self record indexed");
                let self_key = &ps_keys[self_index];
                if edge.higher {
                    (self_key.clone(), other)
                } else {
                    (other, self_key.clone())
                }
            }
            _ => {
                out.push_str(&comment_line(
                    &format!(
                        "{}@{}: override reference `{}` ambiguous across {} active versions → omitted (engine D-02 refuses silent pick)",
                        record.rule_id,
                        record.rule_version,
                        edge.reference,
                        candidates.len()
                    ),
                    2,
                ));
                continue;
            }
        };
        if over != under && emitted.insert((over.clone(), under.clone())) {
            out.push_str(&comment_line(
                &format!("{} precedes-priority over to {}", record.rule_id, id),
                2,
            ));
            out.push_str(&format!(
                "    <lrml:OverrideStatement>\n\
                 \x20     <lrml:Override over=\"#{over}\" under=\"#{under}\"/>\n\
                 \x20   </lrml:OverrideStatement>\n"
            ));
        }
    }
    Ok(out)
}

/// 單條規則 → PrescriptiveStatement（＋Penalty/Reparation）。
fn render_record(
    record: &RuleRecord,
    ps_key: &str,
    atom_counter: &mut usize,
) -> Result<String, String> {
    let label = format!("{}@{}", record.rule_id, record.rule_version);
    let strength = match record.deontic.strength.as_str() {
        "mandatory" | "strict" => "lrml:StrictStrength",
        "optional" | "defeasible" => "lrml:DefeasibleStrength",
        other => {
            return Err(format!(
                "{label}: deontic.strength `{other}` has no verified LegalRuleML mapping — refuse to export (fail-closed)"
            ));
        }
    };
    let deontic = deontic_element(&record.deontic.modality, &label)?;

    // ── if：條件樹 atom ＋ 證據 atom ─────────────────────────────────
    let mut cond_atoms = condition_atoms(&record.condition, &label, atom_counter)?;
    append_evidence_atoms(record, &label, &mut cond_atoms, atom_counter)?;
    if cond_atoms.is_empty() {
        return Err(format!(
            "{label}: no verifiable condition atoms — refuse to emit an if-less rule (fail-closed)"
        ));
    }
    let rule_if = match cond_atoms.len() {
        0 => String::new(),
        1 => format!(
            "        <ruleml:if>\n{}        </ruleml:if>\n",
            cond_atoms[0]
        ),
        _ => format!(
            "        <ruleml:if>\n          <ruleml:And>\n{}          </ruleml:And>\n        </ruleml:if>\n",
            cond_atoms.join("")
        ),
    };

    // ── then：deontic 節點（must-* atom ＋ Bearer slot）─────────────
    let mut head_atoms = String::new();
    for before in &record.sequencing.required_before {
        head_atoms.push_str(&atom_xml(
            "ekp:must-have-before",
            &label,
            atom_counter,
            &[before.as_str()],
        ));
    }
    for after in &record.sequencing.forbidden_after {
        head_atoms.push_str(&atom_xml(
            "ekp:must-not-be-followed-by",
            &label,
            atom_counter,
            &[after.as_str()],
        ));
    }
    if let Some(deadline) = &record.sequencing.deadline {
        let anchor = deadline
            .get("anchor")
            .and_then(Value::as_str)
            .unwrap_or("activity");
        let reference = deadline
            .get("ref")
            .and_then(Value::as_str)
            .unwrap_or_default();
        let duration = deadline
            .get("duration_iso")
            .and_then(Value::as_str)
            .unwrap_or_default();
        head_atoms.push_str(&comment_line(
            &format!(
                "deadline anchored at {anchor}({reference}); strict > after {duration} (engine D-04)"
            ),
            8,
        ));
        head_atoms.push_str(&atom_xml(
            "ekp:must-meet-deadline",
            &label,
            atom_counter,
            &[reference, duration],
        ));
    }
    if let Some(lp) = &record.sequencing.loop_policy {
        head_atoms.push_str(&atom_xml(
            "ekp:must-stop-rework",
            &label,
            atom_counter,
            &[
                &lp.failures_cap.to_string(),
                lp.doc_ref.trim_start_matches('§'),
            ],
        ));
    }
    if head_atoms.is_empty() {
        // 規範頭備位內容：subject 活動（依 modality 命名動詞）。
        let acts = Platform::subject_activities(&record.condition);
        let rel = match record.deontic.modality.as_str() {
            "obligation" => "ekp:perform-activity",
            "permission" | "right" => "ekp:permitted-activity",
            "prohibition" => "ekp:forbidden-activity",
            other => {
                return Err(format!(
                    "{label}: modality `{other}` has no verified LegalRuleML mapping (fail-closed)"
                ));
            }
        };
        if acts.is_empty() {
            return Err(format!(
                "{label}: deontic head empty and no subject activity resolvable — refuse to export"
            ));
        }
        for act in acts {
            head_atoms.push_str(&atom_xml(rel, &label, atom_counter, &[act.as_str()]));
        }
    }

    let bearer_slot = match record.subject.actor_role.as_deref() {
        Some(role) if !role.is_empty() => format!(
            "          <ruleml:slot>\n\
             \x20           <lrml:Bearer iri=\"ekp:role-{}\"/>\n\
             \x20           <ruleml:Var>bearer</ruleml:Var>\n\
             \x20         </ruleml:slot>\n",
            curie_segment(role)
        ),
        _ => String::new(),
    };

    let mut out = String::new();
    out.push_str(&comment_line(&label, 2));
    out.push_str(&format!(
        "    <lrml:PrescriptiveStatement key=\"{ps_key}\">\n\
         \x20     <ruleml:Rule key=\"rk-{ps_key}\" closure=\"universal\">\n\
         \x20       <lrml:hasStrength>\n\
         \x20         <{strength} key=\"st-{ps_key}\"/>\n\
         \x20       </lrml:hasStrength>\n"
    ));
    out.push_str(&rule_if);
    out.push_str(&format!(
        "        <ruleml:then>\n\
         \x20         <lrml:SuborderList>\n\
         \x20           <{}>\n{bearer_slot}{head_atoms}           </{}>\n\
         \x20         </lrml:SuborderList>\n\
         \x20       </ruleml:then>\n\
         \x20     </ruleml:Rule>\n    </lrml:PrescriptiveStatement>\n",
        deontic, deontic,
    ));

    match record.sequencing.on_violation.as_deref() {
        None | Some("none") | Some("") => {}
        Some(consequence) => out.push_str(&consequence_block(
            &label,
            ps_key,
            consequence,
            atom_counter,
        )?),
    }
    Ok(out)
}

fn deontic_element(modality: &str, label: &str) -> Result<&'static str, String> {
    match modality {
        "obligation" => Ok("lrml:Obligation"),
        "prohibition" => Ok("lrml:Prohibition"),
        "permission" => Ok("lrml:Permission"),
        "right" => Ok("lrml:Right"),
        other => Err(format!(
            "{label}: deontic.modality `{other}` has no verified node (official set Obligation/Prohibition/Permission/Right) — refuse to export (fail-closed)"
        )),
    }
}

/// 條件樹 → atoms；`all` 攤平；`any`/`not` 拒匯（無官方核實映射）。
fn condition_atoms(
    condition: &Option<ConditionNode>,
    label: &str,
    counter: &mut usize,
) -> Result<Vec<String>, String> {
    fn walk(
        node: &ConditionNode,
        label: &str,
        counter: &mut usize,
        out: &mut Vec<String>,
    ) -> Result<(), String> {
        match node {
            ConditionNode::Leaf { predicate } => {
                let value_str = value_lexical(&predicate.value, label)?;
                let rel = format!(
                    "ekp:cond-{}-{}",
                    curie_segment(&predicate.field),
                    curie_segment(&predicate.op)
                );
                out.push(atom_xml(&rel, label, counter, &[value_str.as_str()]));
                Ok(())
            }
            ConditionNode::All { all } => {
                for child in all {
                    walk(child, label, counter, out)?;
                }
                Ok(())
            }
            ConditionNode::Any { .. } => Err(format!(
                "{label}: condition kind `any` is engine-supported but has no verified LegalRuleML construct in research/legalruleml-notes.md (no invented Or) — refuse to export (fail-closed)"
            )),
            ConditionNode::Not { .. } => Err(format!(
                "{label}: condition kind `not` is engine-supported but has no verified LegalRuleML construct in research/legalruleml-notes.md — refuse to export (fail-closed)"
            )),
        }
    }
    let mut out = Vec::new();
    if let Some(node) = condition {
        walk(node, label, counter, &mut out)?;
    }
    Ok(out)
}

/// 證據需求 atoms（相鄰註解分組；metadata 條款逐一 atom 化）。
fn append_evidence_atoms(
    record: &RuleRecord,
    label: &str,
    atoms: &mut Vec<String>,
    counter: &mut usize,
) -> Result<(), String> {
    for (index, req) in record.evidence_requirements.iter().enumerate() {
        atoms.push(format!(
            "        <!-- evidence[{index}]: {} min={} -->\n",
            esc_comment(&req.evidence_type),
            req.min_count
        ));
        atoms.push(atom_xml(
            &format!("ekp:evidence-{}", curie_segment(&req.evidence_type)),
            label,
            counter,
            &[req.min_count.to_string().as_str()],
        ));
        for constraint in &req.metadata_constraints {
            let value_str = value_lexical(&constraint.value, label)?;
            atoms.push(atom_xml(
                &format!(
                    "ekp:evidence-meta-{}-{}",
                    curie_segment(&constraint.field),
                    curie_segment(&constraint.op)
                ),
                label,
                counter,
                &[value_str.as_str()],
            ));
        }
    }
    Ok(())
}

/// on_violation → PenaltyStatement + Reparation（官方骨架；後果 gala 值入 IRI）。
fn consequence_block(
    label: &str,
    ps_key: &str,
    consequence: &str,
    counter: &mut usize,
) -> Result<String, String> {
    let mut out = comment_line(
        &format!(
            "{label}: on_violation={consequence} (official Penalty/Reparation, research note §2.6)"
        ),
        2,
    );
    let atom = atom_xml(
        &format!("ekp:violation-consequence-{}", curie_segment(consequence)),
        label,
        counter,
        &[label],
    );
    out.push_str(&format!(
        "    <lrml:PenaltyStatement key=\"pen-{ps_key}\">\n\
         \x20     <lrml:SuborderList>\n\
         \x20       <lrml:Obligation key=\"obl-{ps_key}\">\n{atom}        </lrml:Obligation>\n\
         \x20     </lrml:SuborderList>\n\
         \x20     <lrml:Reparation key=\"repa-{ps_key}\">\n\
         \x20       <lrml:appliesPenalty keyref=\"#pen-{ps_key}\"/>\n\
         \x20       <lrml:toPrescriptiveStatement keyref=\"#{ps_key}\"/>\n\
         \x20     </lrml:Reparation>\n\
         \x20   </lrml:PenaltyStatement>\n"
    ));
    Ok(out)
}

/// Atom：`<ruleml:Atom key><ruleml:Rel @iri/><ruleml:Ind ords.../></…>`。
/// 參數順序有語義（筆記 §2.6 positional children），依呼叫端註解定序。
fn atom_xml(rel_iri: &str, label: &str, counter: &mut usize, args: &[&str]) -> String {
    *counter += 1;
    let key = format!("a{}", *counter);
    let mut out = format!(
        "          <ruleml:Atom key=\"{key}\"><!-- {} -->\n\
         \x20           <ruleml:Rel iri=\"{}\"/>\n",
        esc_comment(label),
        esc_attr(rel_iri)
    );
    for arg in args {
        out.push_str(&format!(
            "            <ruleml:Ind>{}</ruleml:Ind>\n",
            esc_text(arg)
        ));
    }
    out.push_str("          </ruleml:Atom>\n");
    out
}

/// Value 的詞法值（null／巢狀複合無法忠實表達 → Err）。
fn value_lexical(value: &Value, label: &str) -> Result<String, String> {
    match value {
        Value::Null => Err(format!(
            "{label}: null value has no lexical form in an atom (fail-closed)"
        )),
        Value::Bool(b) => Ok(b.to_string()),
        Value::Number(n) => Ok(n.to_string()),
        Value::String(s) => Ok(s.clone()),
        Value::Array(items) => {
            let mut joined = String::new();
            for (i, item) in items.iter().enumerate() {
                if i > 0 {
                    joined.push(';');
                }
                match item {
                    Value::Null => {
                        return Err(format!("{label}: null member in list value (fail-closed)"));
                    }
                    Value::String(s) => joined.push_str(s),
                    Value::Bool(b) => joined.push_str(&b.to_string()),
                    Value::Number(n) => joined.push_str(&n.to_string()),
                    _ => {
                        return Err(format!(
                            "{label}: nested composite in list value unsupported (fail-closed)"
                        ));
                    }
                }
            }
            Ok(joined)
        }
        Value::Object(_) => Err(format!(
            "{label}: object value unsupported in atom (fail-closed)"
        )),
    }
}

fn esc_text(text: &str) -> String {
    text.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
}

fn esc_attr(text: &str) -> String {
    esc_text(text).replace('"', "&quot;")
}

fn esc_comment(text: &str) -> String {
    text.replace("--", "- -")
}

// ─── 匯出的自助驗證器（筆記 §四注意事項 6 的 schema-外子集）────────────

/// compact 匯出的全域檢查：良構、禁用名、鍵唯一/引用可解析、頂層順序。
pub fn validate_compact_export(xml: &str) -> Result<(), String> {
    check_well_formed(xml)?;
    check_names(xml)?;
    check_ids_and_refs(xml)?;
    check_top_level_order(xml)?;
    Ok(())
}

/// 移除 XML 註解（機器檢查僅對元素本體；並保證檢查物件為可定址純文字）。
fn strip_comments(xml: &str) -> String {
    let chars: Vec<char> = xml.chars().collect();
    let mut out = String::with_capacity(xml.len());
    let mut i = 0usize;
    while i < chars.len() {
        if chars[i] == '<' && chars.get(i + 1) == Some(&'!') && chars.get(i + 2) == Some(&'-') {
            let mut j = i + 4;
            let mut closed = false;
            while j + 2 < chars.len() {
                if chars[j] == '-' && chars[j + 1] == '-' && chars[j + 2] == '>' {
                    closed = true;
                    break;
                }
                j += 1;
            }
            if !closed {
                break;
            }
            i = j + 3;
            continue;
        }
        out.push(chars[i]);
        i += 1;
    }
    out
}

fn check_well_formed(xml: &str) -> Result<(), String> {
    let chars: Vec<char> = xml.chars().collect();
    let mut stack: Vec<String> = Vec::new();
    let mut i = 0usize;
    while i < chars.len() {
        if chars[i] != '<' {
            i += 1;
            continue;
        }
        match chars.get(i + 1) {
            Some('!') => {
                // 註解（以 "-->" 終止；形狀缺失一律 Err）。
                let mut j = i + 4;
                let mut closed = false;
                while j + 2 < chars.len() {
                    if chars[j] == '-' && chars[j + 1] == '-' && chars[j + 2] == '>' {
                        closed = true;
                        break;
                    }
                    j += 1;
                }
                if !closed {
                    return Err("unterminated comment".to_string());
                }
                i = j + 3;
            }
            Some('/') => {
                let mut j = i + 2;
                let mut name = String::new();
                while j < chars.len() && chars[j] != '>' {
                    name.push(chars[j]);
                    j += 1;
                }
                match stack.pop() {
                    Some(open) if open == name => {}
                    Some(open) => {
                        return Err(format!("mismatched close `</{name}>` (open `<{open}>`)"));
                    }
                    None => return Err(format!("stray close `</{name}>`")),
                }
                i = j + 1;
            }
            _ => {
                let mut j = i + 1;
                let mut name = String::new();
                while j < chars.len() && !matches!(chars[j], '>' | ' ' | '/' | '\n' | '\t' | '\r') {
                    name.push(chars[j]);
                    j += 1;
                }
                // 自閉判定：找標籤結尾前最後的非空白字元。
                let mut k = j;
                let mut in_quote = false;
                let mut last_significant = ' ';
                while k < chars.len() {
                    match chars[k] {
                        '"' => in_quote = !in_quote,
                        '>' if !in_quote => break,
                        c if !c.is_whitespace() => last_significant = c,
                        _ => {}
                    }
                    k += 1;
                }
                if last_significant != '/' {
                    stack.push(name);
                }
                i = k + 1;
            }
        }
    }
    if !stack.is_empty() {
        return Err(format!("unclosed elements: {stack:?}"));
    }
    Ok(())
}

fn check_names(xml: &str) -> Result<(), String> {
    let body = strip_comments(xml);
    for name in FORBIDDEN_NAMES {
        if body.contains(name) {
            return Err(format!(
                "export contains `{name}` — construct does not exist in LegalRuleML 1.0 (research note §2.11)"
            ));
        }
    }
    Ok(())
}

/// @key 唯一性與 @keyref / @over / @under 引用可解析性。
/// 以字節層掃描（並先剝註解），避免多字節字元破壞字節索引。
fn check_ids_and_refs(xml: &str) -> Result<(), String> {
    let body = strip_comments(xml);
    let bytes = body.as_bytes();
    let patterns: [(&[u8], bool); 4] = [
        (b"key=\"", true),
        (b"keyref=\"#", false),
        (b"over=\"#", false),
        (b"under=\"#", false),
    ];
    let mut marks: Vec<(usize, usize, bool)> = Vec::new();
    for (needle, is_key) in patterns {
        let mut cursor = 0usize;
        while cursor + needle.len() <= bytes.len() {
            if bytes[cursor..cursor + needle.len()] == *needle {
                marks.push((cursor, needle.len(), is_key));
                cursor += needle.len();
            } else {
                cursor += 1;
            }
        }
    }
    marks.sort_unstable();
    let mut keys: BTreeSet<String> = BTreeSet::new();
    let mut refs: Vec<String> = Vec::new();
    for (pos, needle_len, is_key) in marks {
        let start = pos + needle_len;
        let Some(rel_end) = body[start..].find('"') else {
            return Err("unterminated ID attribute".to_string());
        };
        let value = body[start..start + rel_end].to_string();
        if value.is_empty() {
            return Err("empty ID attribute".to_string());
        }
        if is_key {
            // xsd:ID 保守白名單（NCName 子集；首字元非數字/連字符）。
            let ok_chars = value
                .chars()
                .all(|c| c.is_ascii_alphanumeric() || matches!(c, '_' | '-' | '.'));
            let ok_start = value.starts_with(|c: char| c.is_ascii_alphabetic() || c == '_');
            if !ok_chars || !ok_start {
                return Err(format!("key `{value}` is not a valid xsd:ID"));
            }
            if !keys.insert(value.clone()) {
                return Err(format!("duplicate key `{value}` (xsd:ID violation)"));
            }
        } else {
            refs.push(value);
        }
    }
    for reference in refs {
        if !keys.contains(&reference) {
            return Err(format!(
                "reference `#{reference}` does not resolve to any key"
            ));
        }
    }
    Ok(())
}

fn check_top_level_order(xml: &str) -> Result<(), String> {
    let body = strip_comments(xml);
    let order: [(&str, usize); 6] = [
        ("Prefix", find_top(&body, "<lrml:Prefix ")),
        ("LegalSources", find_top(&body, "<lrml:LegalSources")),
        ("Times", find_top(&body, "<lrml:Times>")),
        (
            "TemporalCharacteristics",
            find_top(&body, "<lrml:TemporalCharacteristics"),
        ),
        ("Associations", find_top(&body, "<lrml:Associations")),
        ("Statements", find_top(&body, "<lrml:Statements")),
    ];
    let mut last: Option<usize> = None;
    for (name, pos) in order {
        if pos == 0 {
            continue; // 缺席該類合法（* 皆可零次）
        }
        if let Some(prev) = last
            && pos < prev
        {
            return Err(format!(
                "top-level ordering violated: {name} appears before a later category (§5.16 four category order)"
            ));
        }
        last = Some(pos);
    }
    Ok(())
}

fn find_top(body: &str, needle: &str) -> usize {
    body.find(needle).map_or(0, |i| i + 1)
}

